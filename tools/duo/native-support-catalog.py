"""Check/regenerate Duet's catalog from the two supplied native source worktrees."""
import argparse
import difflib
import importlib.util
from pathlib import Path
import re
import sys

PRIVATE_PEANUTS = {"0100F43008C44000", "0100F7E00C70E000"}
CATALOG = Path(__file__).resolve().parents[2] / "src/android/app/src/main/assets/native_games.tsv"


def profiles(root, engine):
    spec = importlib.util.spec_from_file_location(engine + "_profiles", root / "dm/games/game.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {g.id: g for g in module.all_games()}


def supported(root, engine, games):
    props = (root / "android/app/gradle.properties").read_text(encoding="utf-8")
    declared = next(line.split("=", 1)[1] for line in props.splitlines() if line.startswith("nxGames="))
    ids = {value.strip() for value in declared.split(",") if value.strip()}
    if engine == "peanuts":
        # Published Android titles, private additions, and declared Switch 1 bring-ups.
        text = (root / "README.md").read_text(encoding="utf-8")
        return (set(re.findall(r"\| `((?:0100)[0-9A-F]{12})` \|", text)) |
                PRIVATE_PEANUTS | {title for title in ids if title.startswith("0100")})
    ids = {title for title in ids if title.startswith("0400")}
    ready = set()
    for title, game in games.items():
        path = game.dir / "readiness.tsv"
        if title.startswith("0400") and path.is_file() and any(
            row in {"status\tplayable", "status\tbring-up"}
            for row in path.read_text(encoding="utf-8").splitlines()
        ):
            ready.add(title)
    if ids != ready:
        raise ValueError(f"Banana's Android declaration and readiness differ: {sorted(ids ^ ready)}")
    return ids


def render(peanuts, banana):
    rows = []
    for engine, root in (("peanuts", peanuts), ("banana", banana)):
        games = profiles(root, engine)
        for title in sorted(supported(root, engine, games)):
            if title not in games:
                raise ValueError(f"{engine}: missing supported profile {title}")
            game = games[title]
            android = game.words("android_builds", "")
            shaders = game.words("shader_versions", "")
            accepted = 0
            for version, build in game.builds().items():
                if android and version not in android:
                    continue
                if version not in shaders:
                    print(f"{engine}/{title}/{version}: registered code build; shader coverage must be checked during Prepare",
                          file=sys.stderr)
                modules = [f"{name}={value}" for name, value in build.items() if name != "display"]
                if not any(value.startswith("main=") for value in modules):
                    raise ValueError(f"{title}/{version}: no main build identity")
                display = build["display"] if build["display"] not in {"", "?"} else version
                rows.append([engine, game.get("program_id", title), str(int(version.removeprefix("v"))),
                             display, game.get("name"), *modules])
                accepted += 1
            if not accepted:
                raise ValueError(f"{engine}/{title}: no registered Android code version")
    header = ("# SPDX-License-Identifier: GPL-3.0-or-later\n"
              "# Generated by tools/duo/native-support-catalog.py from the supplied native source worktrees.\n"
              "# Peanuts: published Switch 1 Android list, private additions and declared Android bring-ups.\n"
              "# Banana: declared Android Switch 2 profiles. Prepare independently verifies shader coverage.\n"
              "# engine<TAB>program ID<TAB>version<TAB>display version<TAB>title<TAB>module=build ID ...\n")
    return header + "".join("\t".join(row) + "\n" for row in sorted(rows, key=lambda r: (r[0], r[1], int(r[2]))))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--peanuts", type=Path, required=True, help="private Peanuts source worktree")
    parser.add_argument("--banana", type=Path, required=True, help="Banana source worktree")
    parser.add_argument("--write", action="store_true", help="replace the generated catalog; default only checks")
    args = parser.parse_args()
    expected = render(args.peanuts.resolve(), args.banana.resolve())
    actual = CATALOG.read_text(encoding="utf-8")
    if expected == actual:
        print("Native support catalog matches both source worktrees.")
        return 0
    sys.stdout.writelines(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True),
                                             fromfile=str(CATALOG), tofile="source-derived catalog"))
    if args.write:
        CATALOG.write_text(expected, encoding="utf-8", newline="\n")
        print("Updated", CATALOG)
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
